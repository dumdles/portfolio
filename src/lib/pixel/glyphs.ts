/**
 * Pixel glyphs, drawn by hand on a grid.
 *
 * Each glyph is a list of frames, and each frame a list of rows:
 *   "#"  ink, rendered in currentColor
 *   "+"  accent, rendered in the glyph's accent colour (brand by default)
 *   "."  empty
 *
 * Frame 0 is the resting state. Frame 1, where present, is what the glyph
 * does on hover, either swapped in once or alternated as a two-frame loop;
 * <PixelGlyph> decides which.
 *
 * Generated from a validated source so every row is the declared width.
 * Edit freely, but keep every row in a frame the same length.
 */

export interface GlyphData {
  w: number;
  h: number;
  frames: string[][];
}

